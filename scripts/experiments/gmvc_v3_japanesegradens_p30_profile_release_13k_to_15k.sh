  GMVC_INTRINSIC_USE_DC_PROXY="True" \
  GMVC_FREEZE_GEOMETRY="False" \
  GMVC_TRAIN_FEATURES_DC="False" \
  GMVC_TRAIN_FEATURES_REST="False" \
  "${REPO_DIR}/scripts/experiments/gmvc_phase_b_common.sh"
