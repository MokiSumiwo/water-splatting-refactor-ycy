#!/usr/bin/env bash
set -euo pipefail

REPO_DIR="/mnt/new/home_old/ycy/water-splatting-refactor"

VARIANT="${VARIANT:-MHOLD}"
GPU="${GPU:-6}"
SEED="${SEED:-42}"
LOAD_STEP="${LOAD_STEP:-13000}"
TARGET_FINAL_STEP="${TARGET_FINAL_STEP:-15000}"
SOURCE_STAMP_BASE="${SOURCE_STAMP:-20260806_gmvc_v3_japanesegradens_r500_profile_persistence_3k}"
STAMP_BASE="${STAMP:-20260806_gmvc_v3_japanesegradens_p30_profile_release_13k_to_15k}"
LOG_ROOT="${LOG_ROOT:-${REPO_DIR}/logs}"
DEFAULT_STEPS_PER_SAVE="1000"
MEDIUM_HOLD_ENABLED="False"
MEDIUM_HOLD_START_STEP="13001"
MEDIUM_HOLD_STOP_STEP="${TARGET_FINAL_STEP}"

A0_SOURCE_EXP="gmvc_v3_a0_profile_persistence3k_japanesegradens_redsea_seed${SEED}_step10000_to_13000"
P30_SOURCE_EXP="gmvc_v3_r500_p30_profile_persistence3k_japanesegradens_redsea_seed${SEED}_step10000_to_13000"
A0_SOURCE_CKPT="${A0_SOURCE_CKPT:-${REPO_DIR}/outputs/${A0_SOURCE_EXP}/water-splatting/${A0_SOURCE_EXP}_${SOURCE_STAMP_BASE}_a0/nerfstudio_models/step-000013000.ckpt}"
