TRAIN_BANK="${TRAIN_BANK:-${REPO_DIR}/renders/gmvc_v3_geometry_track_banks/japanesegradens_redsea_m1_step10000_train_s4096/gmvc_track_bank.pt}"

case "${VARIANT}" in
  A0|a0)
    SLUG="a0"
    SOURCE_CKPT="${A0_SOURCE_CKPT}"
    GMVC_ON="False"
    PROFILE_SCHEDULE="constant"
    PROFILE_LAMBDA="0.0"
    OBJECT_LAMBDA="0.0"
    ;;
  A0_MHOLD|a0_mhold|A0-MHOLD|a0-mhold)
    SLUG="a0_mhold"
    SOURCE_CKPT="${A0_SOURCE_CKPT}"
    GMVC_ON="True"
    PROFILE_SCHEDULE="stop"
    PROFILE_LAMBDA="0.0"
    OBJECT_LAMBDA="0.004"
    PROFILE_DECAY_START_STEP="13000"
    MEDIUM_HOLD_ENABLED="True"
    DEFAULT_STEPS_PER_SAVE="500"
    ;;
  A0_PHASE|a0_phase|A0-PHASE|a0-phase)
    SLUG="a0_phase"
    SOURCE_CKPT="${A0_SOURCE_CKPT}"
    GMVC_ON="True"
    PROFILE_SCHEDULE="stop"
    PROFILE_LAMBDA="0.0"
    OBJECT_LAMBDA="0.004"
    PROFILE_DECAY_START_STEP="13000"
    DEFAULT_STEPS_PER_SAVE="500"
    ;;
  MHOLD|mhold|P30_MHOLD|p30_mhold|P30-MHOLD|p30-mhold)
    SLUG="mhold"
    SOURCE_CKPT="${P30_SOURCE_CKPT}"
    GMVC_ON="True"
    PROFILE_SCHEDULE="stop"
    PROFILE_LAMBDA="30"
    OBJECT_LAMBDA="0.004"
    PROFILE_DECAY_START_STEP="13000"
    MEDIUM_HOLD_ENABLED="True"
    DEFAULT_STEPS_PER_SAVE="500"
    ;;
  *)
    echo "Unknown VARIANT=${VARIANT}. Use A0, A0_MHOLD, A0_PHASE, or MHOLD." >&2
    exit 2
    ;;
esac

PROFILE_DECAY_START_STEP="${PROFILE_DECAY_START_STEP:-13000}"

if [[ ! -f "${SOURCE_CKPT}" ]]; then
  echo "Missing source checkpoint for ${VARIANT}: ${SOURCE_CKPT}" >&2
  exit 1
fi
if [[ "${GMVC_ON}" == "True" && ! -f "${TRAIN_BANK}" ]]; then
  echo "Missing fixed train bank: ${TRAIN_BANK}" >&2
  exit 1
fi

EXPERIMENT_NAME_DEFAULT="gmvc_v3_japanesegradens_p30_release_${SLUG}_seed${SEED}_step${LOAD_STEP}_to_${TARGET_FINAL_STEP}"
STAMP="${STAMP_BASE}_${SLUG}"
GRAD_LOG="${LOG_ROOT}/gmvc_v3_japanesegradens_p30_release_${SLUG}_${STAMP_BASE}.jsonl"

