STAMP="${STAMP:-$(date -u +%Y%m%d_%H%M%S)}"
EXPERIMENT_NAME="${EXPERIMENT_NAME:-mvgar_${EXPERIMENT_TAG}_${SCENE_SLUG}_seed${SEED}_${MAX_NUM_ITERATIONS}}"
TIMESTAMP="${TIMESTAMP:-${EXPERIMENT_NAME}_${STAMP}}"
RUN_EVAL="${RUN_EVAL:-1}"
RUN_CLOSURE_DIAG="${RUN_CLOSURE_DIAG:-0}"

DEPTH_DIR="${DEPTH_DIR:-${DATA_PATH}/depthAnything_u16}"
MVGAR_PSEUDO_DEPTH_DIR="${MVGAR_PSEUDO_DEPTH_DIR:-${OUTPUT_DIR}/mvgar_pseudo_depth/${SCENE_SLUG}_train}"
BUILD_MVGAR_DEPTH="${BUILD_MVGAR_DEPTH:-1}"
FORCE_BUILD_MVGAR_DEPTH="${FORCE_BUILD_MVGAR_DEPTH:-0}"
MVGAR_PREPROCESS_EXTRA_ARGS="${MVGAR_PREPROCESS_EXTRA_ARGS:---skip-cross-view --ransac-residual-threshold 0.25 --max-median-relative-error 0.25}"

if [[ "${MVGAR_ENABLED:-False}" == "True" || "${MVGAR_DIAGNOSTIC_ONLY:-False}" == "True" || "${MVGAR_DENSIFICATION_ENABLED:-False}" == "True" ]]; then
  if [[ "${BUILD_MVGAR_DEPTH}" == "1" ]]; then
    if [[ "${FORCE_BUILD_MVGAR_DEPTH}" == "1" || ! -f "${MVGAR_PSEUDO_DEPTH_DIR}/metadata.json" ]]; then
      mkdir -p "${MVGAR_PSEUDO_DEPTH_DIR}"
      CUDA_VISIBLE_DEVICES="${GPU}" "${PYTHON}" "${REPO_DIR}/scripts/preprocess/build_mvgar_pseudo_depth.py" \
        --data "${DATA_PATH}" \
        --depth-dir "${DEPTH_DIR}" \
        --output-dir "${MVGAR_PSEUDO_DEPTH_DIR}" \
        --seed "${SEED}" \
        ${MVGAR_PREPROCESS_EXTRA_ARGS}
    fi
  fi
fi

