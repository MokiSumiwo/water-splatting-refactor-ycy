#!/usr/bin/env bash
set -euo pipefail

REPO_DIR="/mnt/new/home_old/ycy/water-splatting-refactor"
PYTHON="${PYTHON:-/opt/anaconda3/envs/water_splatting/bin/python}"

: "${SCENE_SLUG:?Set SCENE_SLUG, e.g. japanesegradens or iui3}"
: "${DATA_PATH:?Set DATA_PATH to the scene directory}"
: "${EXPERIMENT_TAG:?Set EXPERIMENT_TAG, e.g. c2_persistent}"

GPU="${GPU:-6}"
OUTPUT_DIR="${OUTPUT_DIR:-${REPO_DIR}/outputs}"
RENDER_ROOT="${RENDER_ROOT:-${REPO_DIR}/renders}"
LOG_ROOT="${LOG_ROOT:-${REPO_DIR}/logs}"
SEED="${SEED:-42}"
MAX_NUM_ITERATIONS="${MAX_NUM_ITERATIONS:-5000}"
MODEL_NUM_STEPS="${MODEL_NUM_STEPS:-${MAX_NUM_ITERATIONS}}"
STEPS_PER_SAVE="${STEPS_PER_SAVE:-5000}"
SAVE_ONLY_LATEST_CHECKPOINT="${SAVE_ONLY_LATEST_CHECKPOINT:-True}"
STAMP="${STAMP:-$(date -u +%Y%m%d_%H%M%S)}"
EXPERIMENT_NAME="${EXPERIMENT_NAME:-mcgr_${EXPERIMENT_TAG}_${SCENE_SLUG}_seed${SEED}_${MAX_NUM_ITERATIONS}}"
TIMESTAMP="${TIMESTAMP:-${EXPERIMENT_NAME}_${STAMP}}"
RUN_EVAL="${RUN_EVAL:-1}"
RUN_CLOSURE_DIAG="${RUN_CLOSURE_DIAG:-0}"

DEPTH_DIR="${DEPTH_DIR:-${DATA_PATH}/depthAnything_u16}"
MVGAR_PSEUDO_DEPTH_DIR="${MVGAR_PSEUDO_DEPTH_DIR:-${OUTPUT_DIR}/mvgar_pseudo_depth/${SCENE_SLUG}_train}"
MCGR_CORRESPONDENCE_DIR="${MCGR_CORRESPONDENCE_DIR:-${OUTPUT_DIR}/mcgr_correspondences/${SCENE_SLUG}_train}"
BUILD_MVGAR_DEPTH="${BUILD_MVGAR_DEPTH:-1}"
BUILD_MCGR_CORRESPONDENCE="${BUILD_MCGR_CORRESPONDENCE:-1}"
FORCE_BUILD_MVGAR_DEPTH="${FORCE_BUILD_MVGAR_DEPTH:-0}"
FORCE_BUILD_MCGR_CORRESPONDENCE="${FORCE_BUILD_MCGR_CORRESPONDENCE:-0}"
MVGAR_PREPROCESS_EXTRA_ARGS="${MVGAR_PREPROCESS_EXTRA_ARGS:---skip-cross-view --ransac-residual-threshold 0.25 --max-median-relative-error 0.25}"
MCGR_PREPROCESS_EXTRA_ARGS="${MCGR_PREPROCESS_EXTRA_ARGS:-}"

if [[ "${MCGR_ENABLED:-False}" == "True" || "${MCGR_DIAGNOSTIC_ONLY:-False}" == "True" ]]; then
  if [[ "${BUILD_MVGAR_DEPTH}" == "1" ]]; then
    if [[ "${FORCE_BUILD_MVGAR_DEPTH}" == "1" || ! -f "${MVGAR_PSEUDO_DEPTH_DIR}/metadata.json" ]]; then
      mkdir -p "${MVGAR_PSEUDO_DEPTH_DIR}"
      CUDA_VISIBLE_DEVICES="${GPU}" "${PYTHON}" "${REPO_DIR}/scripts/preprocess/build_mvgar_pseudo_depth.py" \
        --data "${DATA_PATH}" \
        --depth-dir "${DEPTH_DIR}" \
        --output-dir "${MVGAR_PSEUDO_DEPTH_DIR}" \
        --seed "${SEED}" \
        ${MVGAR_PREPROCESS_EXTRA_ARGS}
    fi
  fi
  if [[ "${BUILD_MCGR_CORRESPONDENCE}" == "1" ]]; then
    if [[ "${FORCE_BUILD_MCGR_CORRESPONDENCE}" == "1" || ! -f "${MCGR_CORRESPONDENCE_DIR}/metadata.json" ]]; then
      mkdir -p "${MCGR_CORRESPONDENCE_DIR}"
      CUDA_VISIBLE_DEVICES="${GPU}" "${PYTHON}" "${REPO_DIR}/scripts/preprocess/build_mcgr_correspondences.py" \
        --data "${DATA_PATH}" \
        --depth-dir "${DEPTH_DIR}" \
        --pseudo-depth-dir "${MVGAR_PSEUDO_DEPTH_DIR}" \
        --output-dir "${MCGR_CORRESPONDENCE_DIR}" \
        ${MCGR_PREPROCESS_EXTRA_ARGS}
    fi
  fi
fi

env \
  GPU="${GPU}" \
  PYTHON="${PYTHON}" \
  DATA_PATH="${DATA_PATH}" \
  OUTPUT_DIR="${OUTPUT_DIR}" \
  RENDER_ROOT="${RENDER_ROOT}" \
  LOG_ROOT="${LOG_ROOT}" \
  EXPERIMENT_NAME="${EXPERIMENT_NAME}" \
  TIMESTAMP="${TIMESTAMP}" \
  STAMP="${STAMP}" \
  MAX_NUM_ITERATIONS="${MAX_NUM_ITERATIONS}" \
  MODEL_NUM_STEPS="${MODEL_NUM_STEPS}" \
  STEPS_PER_SAVE="${STEPS_PER_SAVE}" \
  SAVE_ONLY_LATEST_CHECKPOINT="${SAVE_ONLY_LATEST_CHECKPOINT}" \
  SEED="${SEED}" \
  MEDIUM_CONTEXT_MODE="dir_xy_camera" \
  BINF_MODE="tied" \
  BG_COLOR_WEIGHT="0.0" \
  BG_MEDIUM_RENDER_WEIGHT="0.0" \
  BG_TAIL_RENDER_WEIGHT="0.0" \
  BG_CLEAR_GAUSSIAN_WEIGHT="0.0" \
  BG_CLEAR_CHROMA_WEIGHT="0.0" \
  MEDIUM_EXPLAINABILITY_ENABLED="False" \
  LAMBDA_MEDIUM_EXPLAINABILITY="0.0" \
  TRAINING_GRADIENT_ROUTING_ENABLED="False" \
  BUDGETED_CAPACITY_ENABLED="False" \
  LAMBDA_BUDGETED_CAPACITY="0.0" \
  CORE_ZERO_CAPACITY_ENABLED="False" \
  LAMBDA_CORE_ZERO_CAPACITY="0.0" \
  CAPACITY_CONTROL_ENABLED="False" \
  HALO_CAPACITY_ENABLED="False" \
  LAMBDA_HALO_CAPACITY="0.0" \
  LAMBDA_PROXY_CLEAR_LUMA="0.0" \
  OBJECT_RADIANCE_BUDGET_ENABLED="False" \
  LAMBDA_OBJECT_RADIANCE_BUDGET="0.0" \
  CLEAR_PROXY_ENABLED="False" \
  BACKGROUND_GRADIENT_SURGERY_ENABLED="False" \
  BACKGROUND_DENSIFICATION_ENABLED="False" \
  BACKGROUND_DENSIFICATION_DIAGNOSTIC_ONLY="True" \
  OPACITY_ACCUMULATION_DIAGNOSTIC_ENABLED="False" \
  FG_TRANS_WEIGHT="0.0" \
  LAMBDA_PSEUDO_DEPTH="0.0" \
  LAMBDA_MEDIUM_CONTEXT_RESIDUAL="0.0" \
  GAUSSIAN_CLEANUP_ENABLED="False" \
  MVGAR_ENABLED="False" \
  MVGAR_DIAGNOSTIC_ONLY="False" \
  MVGAR_DENSIFICATION_ENABLED="False" \
  MVGAR_PSEUDO_DEPTH_DIR="${MVGAR_PSEUDO_DEPTH_DIR}" \
  LAMBDA_MVGAR_SURFACE="0.0" \
  MCGR_ENABLED="${MCGR_ENABLED:-False}" \
  MCGR_DIAGNOSTIC_ONLY="${MCGR_DIAGNOSTIC_ONLY:-True}" \
  MCGR_CORRESPONDENCE_DIR="${MCGR_CORRESPONDENCE_DIR}" \
  MCGR_START_STEP="${MCGR_START_STEP:-1000}" \
  MCGR_STOP_STEP="${MCGR_STOP_STEP:-10000}" \
  MCGR_RESIDUAL_BANK_DOWNSCALE="${MCGR_RESIDUAL_BANK_DOWNSCALE:-4}" \
  MCGR_RESIDUAL_EMA_DECAY="${MCGR_RESIDUAL_EMA_DECAY:-0.80}" \
  MCGR_RESIDUAL_MAX_AGE_EPOCHS="${MCGR_RESIDUAL_MAX_AGE_EPOCHS:-2.0}" \
  MCGR_HIGHPASS_WEIGHT="${MCGR_HIGHPASS_WEIGHT:-0.35}" \
  MCGR_RESIDUAL_MATCH_TAU="${MCGR_RESIDUAL_MATCH_TAU:-0.30}" \
  MCGR_MIN_VALID_NEIGHBORS="${MCGR_MIN_VALID_NEIGHBORS:-2}" \
  MCGR_MIN_VIEW_COUNT="${MCGR_MIN_VIEW_COUNT:-3}" \
  MCGR_MIN_MEAN_CONFIDENCE="${MCGR_MIN_MEAN_CONFIDENCE:-0.30}" \
  MCGR_PERSISTENT_QUANTILE="${MCGR_PERSISTENT_QUANTILE:-0.85}" \
  MCGR_ACCUMULATION_MID="${MCGR_ACCUMULATION_MID:-0.40}" \
  MCGR_ACCUMULATION_TEMP="${MCGR_ACCUMULATION_TEMP:-0.08}" \
  MCGR_DEPTH_STD_KAPPA="${MCGR_DEPTH_STD_KAPPA:-0.25}" \
  MCGR_GRADIENT_COHERENCE_ENABLED="${MCGR_GRADIENT_COHERENCE_ENABLED:-False}" \
  MCGR_GRADIENT_COHERENCE_THRESHOLD="${MCGR_GRADIENT_COHERENCE_THRESHOLD:-0.35}" \
  MCGR_MAX_EXTRA_RATIO_TO_BASE="${MCGR_MAX_EXTRA_RATIO_TO_BASE:-0.20}" \
  MCGR_MAX_EXTRA_FRACTION_PER_REFINE="${MCGR_MAX_EXTRA_FRACTION_PER_REFINE:-0.001}" \
  RUN_EVAL="${RUN_EVAL}" \
  RUN_CLOSURE_DIAG="${RUN_CLOSURE_DIAG}" \
  RUN_FAR_DIAG="0" \
  RUN_REGION_DIAG="0" \
  "${REPO_DIR}/scripts/experiments/backscatter_consistent_binf_iui3_redsea.sh"
